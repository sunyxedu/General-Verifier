    "hair-splitting world that no serious reading of the claim admits is "
    "not a counterexample — inventing one to look rigorous is a false "
    "attack, and it turns into a false refutation downstream. A genuine "
    "counterexample varies the claim's own subject matter; a world that "
    "instead varies background conditions every serious reading of the "
